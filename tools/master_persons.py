def literal(form):
    """The longest run of plain characters that every match of a form contains, or ''. Only
    characters outside groups and classes count, and none that a quantifier governs."""
    atoms, depth, i = [], 0, 0          # the form's top-level atoms: a character, or None
    while i < len(form):
        c, i = form[i], i + 1
        if c == '\\':
            c, i = form[i], i + 1
            atom = None if c.isalnum() else c
        elif c == '[':
            i += form[i] == '^'
            i += form[i] == ']'
            while form[i] != ']':
                i += 2 if form[i] == '\\' else 1
            i += 1
            atom = None
        elif c == '(':
            depth += 1
            continue
        elif c == ')':
            depth -= 1
            atom = None
        elif c in '?*+{':
            if c == '{':
                i = form.index('}', i) + 1
            if depth == 0 and atoms:
                atoms[-1] = None
            continue
        elif c == '|':
            if depth == 0:
                return ''
            continue
        else:
            atom = None if c in '.^$' else c
        if depth == 0:
            atoms.append(atom)
    return max(''.join(a or '\0' for a in atoms).split('\0'), key=len)


# Each form is tried only on the blocks that contain its literal, which spares most of the work.
FORMS = [(re.compile(r'(?<![\w])(?:' + f + r')s?(?![\w])'), i, literal(f))
         for i, (_, forms) in enumerate(PERSONS) for f in forms]


def names(text):
    """[(start, end, person)] for the names in one block of the guide. The leftmost match is
    taken, and of the matches that begin at the same place, the longest; a match that
    overlaps one already taken is dropped."""
    found = sorted((m.start(), -m.end(), i) for rx, i, lit in FORMS if lit in text
                   for m in rx.finditer(text))
    out, last = [], 0
    for s, e, i in found:
        if s >= last:
            out.append((s, -e, i))
            last = -e
    return out


def collect(text):
    """Return the names in the guide as [(line, anchor, person, matched text)] and the
    anchors in order."""
    lines = text.split('\n')
    start = next(i for i, l in enumerate(lines) if l.startswith('## <a id="introduction"'))
    end = next(i for i, l in enumerate(lines) if l.startswith('## <a id="scripture-index"'))
    order = re.findall(r'^#{2,6}\s+<a id="([^"]+)"></a>', text, re.M)
    out = []
    for n, anchor, _, block in blocks(lines, start, end):
        block = normalize(block)
        out += [(n, anchor, i, block[s:e]) for s, e, i in names(block)]
    return out, order


