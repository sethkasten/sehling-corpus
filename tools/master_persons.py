def fold(s):
    """A word as it sorts: without accents, case or punctuation."""
    s = unicodedata.normalize('NFKD', s)
    return re.sub(r'[\W_]', '', ''.join(c for c in s if not unicodedata.combining(c))).casefold()


def sort_key(heading):
    """Headings sort word by word up to the first comma or parenthesis, then by the rest. A
    ruler's numeral sorts as a number, before any name: Johann, Johann I, Johann IV,
    Johann Adolf."""
    head, rest = re.match(r'([^,(]*)[,(]?(.*)', heading).groups()

    def words(s):
        return tuple((0, roman(w), '') if roman(w) else (1, 0, fold(w)) for w in s.split())
    return words(head), words(rest)


def build(found, order):
    rank = {a: i for i, a in enumerate(order)}
    sections = {}
    for _, anchor, i, _ in found:
        sections.setdefault(i, set()).add(anchor)
    by_letter = {}
    for i in sorted(sections, key=lambda i: sort_key(PERSONS[i][0])):
        by_letter.setdefault(fold(PERSONS[i][0])[0].upper(), []).append(i)
    out = [' · '.join(f'[{x}](#per-{x.lower()})' for x in by_letter), '']
    for x, people in by_letter.items():
        out += [f'<a id="per-{x.lower()}"></a>**{x}**', '']
        for i in people:
            out.append(f'- {PERSONS[i][0]} — {links(sections[i], rank)}')
        out.append('')
    return '\n'.join(out).rstrip('\n'), len(sections)


def rebuild(text):
    i, j = text.find(START), text.find(END)
    if i < 0 or j < i:
        raise SystemExit('Index of persons markers not found')
    found, order = collect(text)
    body, n = build(found, order)
    named = {f[2] for f in found}
    unnamed = [p[0] for k, p in enumerate(PERSONS) if k not in named]
    return text[:i + len(START)] + '\n' + body + '\n' + text[j:], found, n, unnamed


def main():
    args = sys.argv[1:]
    paths = [a for a in args if not a.startswith('--')]
    path = paths[0] if paths else MASTER
    text = open(path, encoding='utf-8').read()
    new, found, n, unnamed = rebuild(text)
    if '--list' in args:
        for line, anchor, i, matched in found:
            print(f'{line}\t{label(anchor)}\t{PERSONS[i][0]}\t{matched}')
    for name in unnamed:
        print(f'not found in the guide: {name}')
    if '--check' in args:
        print(f'{len(found)} names, {n} persons; the index is {"current" if new == text else "out of date"}')
        sys.exit(1 if unnamed or new != text else 0)
    if '--list' not in args and new != text:
        open(path, 'w', encoding='utf-8').write(new)
    print(f'{len(found)} names, {n} persons')
    sys.exit(1 if unnamed else 0)


if __name__ == '__main__':
    main()
