def resolve(form, pre):
    """The book key for a form and its number, or None."""
    base, full = FORMS[form]
    if base == 'john' and pre:
        base = '1john'
    if base in NUMBERED_BASES:
        if not pre:
            return None
        n = int(pre) if pre.isdigit() else roman(pre)
        key = f'{n}{base[1:]}'
        return key if key in KEY else None
    return None if pre and not base.startswith(pre) else base


def chapters(key):
    return BOOKS[KEY[key]][2]


def ref(key, c1, v1=None, c2=None, v2=None, sfx=''):
    return (KEY[key], c1, v1, c2, v2, sfx)


def parse_ref(s):
    """Parse a reference written as in PROSE ('1 Cor 11:23-29') into a reference tuple."""
    m = re.fullmatch(r'(?:([1-3]) )?(\w+) (\d+)(?::(\d+)(ff?\.)?(?:-(\d+))?)?', s.strip())
    pre, form, c, v, sfx, v2 = m.groups()
    return ref(resolve(form, pre), int(c), int(v) if v else None, None, int(v2) if v2 else None,
               sfx or '')


