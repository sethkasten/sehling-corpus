def prose_refs(m, kind):
    """The references a match of one of the PROSE_RULES stands for."""
    if kind == 'en':
        key = ENGLISH_BOOK[m.group('book')]
        c = ordinal(m.group('ord')) if m.groupdict().get('ord') else int(m.group('num'))
        return [ref(key, c)] if c <= chapters(key) else []
    if kind == 'de':
        key = resolve(m.group('form'), None)
        c = int(m.group('num'))
        return [ref(key, c)] if key and c <= chapters(key) else []
    if kind == 'ps-en':
        nums = [ordinal(o) for o in re.findall(ORD, m.group('ords'))]
        if nums in ([1], [2]):          # "the first psalm or hymn": a count, not a number
            return []
        return [ref('ps', n) for n in nums if n <= 150]
    nums = [int(x) if x.isdigit() else roman(x) for x in re.findall(r'\d+|[IVXLC]+', m.group('nums'))]
    return [ref('ps', n) for n in nums if n and n <= 150]


def normalize(text):
    text = re.sub(r'`[^`]*`', ' ', text)
    text = re.sub(r'(?<!!)\[((?:[^\[\]\\]|\\.|\[[^\]]*\])*)\]\(#[^)\s]+\)', r'\1', text)
    text = text.replace('*', '')
    text = re.sub(r'(?<=[A-Za-z])\[([a-z]+)\](?=[\s.,;:])', r'\1', text)   # Jes[ajae], Gene[sis]
    return re.sub(r'\s+', ' ', text).strip()


def references(text, quote, used):
    """Return [(matched text, reference)] for one block of the guide; quote is true for a
    block quotation, that is, the text of an order."""
    found = []
    for snippet, refs in PROSE:
        while snippet in text:
            used.add(snippet)
            found += [(snippet, parse_ref(r)) for r in refs.split(';')]
            text = text.replace(snippet, ' ' * len(snippet), 1)
    for rule, kind in PROSE_RULES:
        for m in rule.finditer(text):
            refs = prose_refs(m, kind)
            if refs:
                found += [(m.group(0), r) for r in refs]
                text = text[:m.start()] + ' ' * (m.end() - m.start()) + text[m.end():]
    i = 0
    while True:
        m = BOOK_TOKEN.search(text, i)
        if not m:
            break
        i = m.end()
        form, full = m.group('form'), FORMS[m.group('form')][1]
        if full and m.group('dot'):
            continue                    # "The day of Philip and James. 7." is a list, not a verse
        key = resolve(form, m.group('pre'))
        if key is None and m.group('pre') and FORMS[form][0] not in NUMBERED_BASES:
            key = resolve(form, None)   # "3. Psalms 127 and 128": the number is the list's
        if key is None:
            continue
        source = quote or bool(m.group('dot')) or form not in ENGLISH
        refs, j = tail_spec(text, m.end(), key, source, quote or bool(m.group('dot')))
        if refs:
            found += [(text[m.start():j].strip(), r) for r in refs]
            i = j
    return found


def blocks(lines, start, end):
    """Yield (line number, anchor, quotation?, text) for each paragraph, item, row and heading."""
    anchor, cur, cur_n, cur_q = None, [], None, False
    for i in range(start, end):
        line = lines[i]
        h = re.match(r'^#{2,6}\s+<a id="([^"]+)"></a>', line)
        if h:
            if cur:
                yield cur_n, anchor, cur_q, ' '.join(cur)
                cur = []
            anchor = h.group(1)
            yield i + 1, anchor, False, line[h.end():]
            continue
        s = line.strip()
        if not s or s.startswith('<!--') or s.startswith('<div'):
            if cur:
                yield cur_n, anchor, cur_q, ' '.join(cur)
                cur = []
            continue
        q = s.startswith('>')
        t = re.sub(r'^>\s?', '', s) if q else s
        # a numbered line in a quotation is usually a wrapped line of Sehling's text
        new_item = bool(re.match(r'^(?:[-*+]|\d+\.)\s', t) and not q) or t.startswith('|')
        if cur and (q != cur_q or new_item or cur[-1].startswith('|')):
            yield cur_n, anchor, cur_q, ' '.join(cur)
            cur = []
        if not cur:
            cur_n, cur_q = i + 1, q
        cur.append(t)
    if cur:
        yield cur_n, anchor, cur_q, ' '.join(cur)


def collect(text):
    """Return the references of the guide as [(line, anchor, matched text, reference)],
    the anchors in order, and the PROSE entries that matched nothing."""
    lines = text.split('\n')
    start = next(i for i, l in enumerate(lines) if l.startswith('## <a id="introduction"'))
    end = next(i for i, l in enumerate(lines) if l.startswith('## <a id="scripture-index"'))
    order = [a for a in re.findall(r'^#{2,6}\s+<a id="([^"]+)"></a>', text, re.M)]
    used, out = set(), []
    for n, anchor, quote, block in blocks(lines, start, end):
        for matched, r in references(normalize(block), quote, used):
            out.append((n, anchor, matched, r))
    stale = [s for s, _ in PROSE if s not in used]
    return out, order, stale


