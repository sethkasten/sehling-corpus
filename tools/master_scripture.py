def book_name(key):
    name = BOOKS[KEY[key]][1]
    return f'{key[0]} {name}' if key[0].isdigit() else name


def show(r):
    _, c1, v1, c2, v2, sfx = r
    if v1 is None:
        return f'{c1}–{c2}' if c2 else f'{c1}'
    s = f'{c1}:{v1}{sfx}'
    if c2:
        return f'{s}–{c2}:{v2}'
    return f'{s}–{v2}' if v2 else s


def label(anchor):
    """The label of a link to a section: '13.7.2', 'Chapter 3' or 'Introduction'."""
    if re.fullmatch(r'ch\d+', anchor):
        return f'Chapter {anchor[2:]}'
    if anchor.startswith(('introduction', 'intro-', 'repo-')):
        return 'Introduction'
    if anchor.startswith(('conventions', 'conv-')):
        return 'Conventions'
    return expected_label(anchor)


def links(anchors, rank):
    """The links to a set of sections, in the order of the guide. The sections of the front
    matter share a label, as "Introduction", and each label is linked once, to its first
    section."""
    first = {}
    for a in sorted(anchors, key=rank.get):
        first.setdefault(label(a), a)
    return ', '.join(f'[{lab}](#{a})' for lab, a in first.items())


def build(found, order):
    rank = {a: i for i, a in enumerate(order)}
    entries = {}
    for _, anchor, _, r in found:
        entries.setdefault(r, set()).add(anchor)
    by_book = {}
    for r in sorted(entries, key=lambda r: (r[0], r[1], r[2] or 0, r[3] or r[1], r[4] or r[2] or 0, r[5])):
        by_book.setdefault(r[0], []).append(r)
    parts = {'OT': 'Old Testament', 'AP': 'Apocrypha', 'NT': 'New Testament'}
    out = []
    for part, title in parts.items():
        keys = [BOOKS[b][0] for b in by_book if BOOKS[b][3] == part]
        if keys:
            out.append(f'**{title}:** ' + ' · '.join(f'[{book_name(k)}](#scr-{k})' for k in keys))
            out.append('')
    for b, refs in by_book.items():
        key = BOOKS[b][0]
        out.append(f'<a id="scr-{key}"></a>**{book_name(key)}**')
        out.append('')
        for r in refs:
            out.append(f'- {show(r)} — {links(entries[r], rank)}')
        out.append('')
    return '\n'.join(out).rstrip('\n'), len(entries)


def rebuild(text):
    i, j = text.find(START), text.find(END)
    if i < 0 or j < i:
        raise SystemExit('Scripture index markers not found')
    found, order, stale = collect(text)
    body, n = build(found, order)
    return text[:i + len(START)] + '\n' + body + '\n' + text[j:], found, n, stale


def main():
    args = sys.argv[1:]
    paths = [a for a in args if not a.startswith('--')]
    path = paths[0] if paths else MASTER
    text = open(path, encoding='utf-8').read()
    new, found, n, stale = rebuild(text)
    if '--list' in args:
        for line, anchor, matched, r in found:
            print(f'{line}\t{label(anchor)}\t{book_name(BOOKS[r[0]][0])} {show(r)}\t{matched}')
    for s in stale:
        print(f'not found in the guide: {s!r}')
    if '--check' in args:
        print(f'{len(found)} references, {n} entries; the index is {"current" if new == text else "out of date"}')
        sys.exit(1 if stale or new != text else 0)
    if '--list' not in args and new != text:
        open(path, 'w', encoding='utf-8').write(new)
    print(f'{len(found)} references, {n} entries')
    sys.exit(1 if stale else 0)


if __name__ == '__main__':
    main()
