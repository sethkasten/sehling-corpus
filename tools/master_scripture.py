def ordinal(s):
    """The number an English ordinal stands for: 'hundred and twenty-seventh' -> 127."""
    s = s.lower().strip()
    m = re.fullmatch(r'(\d+)(?:st|nd|rd|th)', s)
    if m:
        return int(m.group(1))
    n = 0
    m = re.match(r'(?:one\s+)?hundred(?:\s+and\s+|\s+)(.+)', s)
    if m:
        n, s = 100, m.group(1)
    m = re.fullmatch(r'(\w+)-(\w+)', s)
    if m:
        return n + TENS[m.group(1)] + ORDINALS[m.group(2)]
    return n + ORDINALS[s]


def roman(s):
    vals = {'I': 1, 'V': 5, 'X': 10, 'L': 50, 'C': 100}
    if not re.fullmatch(r'C{0,1}(?:XC|XL|L?X{0,3})(?:IX|IV|V?I{0,3})', s) or not s:
        return None
    total = 0
    for a, b in zip(s, s[1:] + ' '):
        total += -vals[a] if b != ' ' and vals[b] > vals[a] else vals[a]
    return total


