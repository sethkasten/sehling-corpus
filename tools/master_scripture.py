def tail_spec(s, i, key, source, roman_ok):
    """Read the chapter and verses after a book name at s[i:].

    source: the reference is written in the Latin or German way, where "Act. 6, 3"
    is chapter 6, verse 3; in the English way a comma separates chapters ("Ps 67, 51").
    roman_ok: the chapter may be a Roman numeral ("1. Sam. III. 1.").
    Returns (list of references, end position); the list is empty if no chapter follows.
    """
    n = chapters(key)
    m = re.compile(r'\s*(?:am\s+|cap\.\s*|capite\s+|capitel\s+)?').match(s, i)
    j = m.end()
    m = re.compile(r'(\d{1,3})(?![\d\w])').match(s, j)
    if m:
        c = int(m.group(1))
    else:
        m = re.compile(r'([IVXLC]+)(?=[.:,\[]|\s+capite)').match(s, j)
        if not (m and roman_ok):
            return [], i
        c = roman(m.group(1))
        if c is None:
            return [], i
    if not 1 <= c <= n:
        return [], i
    j = m.end()
    # the word "chapter" after the number: "am 2. capitel", "49 cap.", "VI. capite"
    m = re.compile(r'\.?\s*(?:capitel|Capitel|cap\.|capite)(?!\w)').match(s, j)
    if m:
        j = m.end()
    out = []
    v = v2 = c2 = None
    sfx = ''
    verse = re.compile(r'(?::|\[:)(\d{1,3})(?:\])?'                         # 3:16, 4[:9]
                       r'|[.,]?\s*(?:V|v|vers|Vers|verse|Verse)\.?\s*(\d{1,3})(?!\d)'  # 2. vers. 9
                       r'|[.,]?\s*\[(\d{1,3})(?=\s*(?:[-–]\s*\d{1,3}\s*)?(?:ff?\.)?\])')  # 5 [39], 2, [1f.]
    verse_q = re.compile(r',\s*(\d{1,3})(?!\d)(?!\s*\.\s*\d)'                # Act. 6, 3
                         r'|\.\s*(\d{1,3})(?=\s*[.\[]|\s+[a-zäöü]|\s*$)')      # III. 1.
    m = verse.match(s, j) or (verse_q.match(s, j) if source else None)
    if m:
        v = int(next(g for g in m.groups() if g))
        j = m.end()
        m = re.compile(r'(ff?\.)').match(s, j)
        if m:
            sfx, j = m.group(1), m.end()
        m = re.compile(r'\s*[-–—]\s*(\d{1,3})(?::(\d{1,3}))?(?![\d])').match(s, j)
        if m:
            if m.group(2):
                c2, v2 = int(m.group(1)), int(m.group(2))
            else:
                v2 = int(m.group(1))
            j = m.end()
        m = re.compile(r'(ff?\.)?\]').match(s, j)        # close "[1f.]", "[1-7]"
        if m and s[:j].rfind('[') > s[:j].rfind(']'):
            sfx, j = m.group(1) or sfx, m.end()
        out.append(ref(key, c, v, c2, v2, sfx))
        # more verses of the same chapter, "2:18, 21–24", or of another, "9:28; 10:14"
        while True:
            m = re.compile(r',\s*(\d{1,3})(?:\s*[-–]\s*(\d{1,3}))?(?![\d:])').match(s, j)
            if m and not NUMBERED_AHEAD.match(s, m.end()):
                out.append(ref(key, c, int(m.group(1)), None, int(m.group(2)) if m.group(2) else None))
                j = m.end()
                continue
            m = re.compile(r'[,;]\s*(\d{1,3}):(\d{1,3})(?:\s*[-–]\s*(\d{1,3}))?(?!\d)').match(s, j)
            if m and 1 <= int(m.group(1)) <= n:
                c = int(m.group(1))
                out.append(ref(key, c, int(m.group(2)), None, int(m.group(3)) if m.group(3) else None))
                j = m.end()
                continue
            break
    else:
        m = re.compile(r'\s*[-–]\s*(\d{1,3})(?![\d:])').match(s, j)
        if m and c < int(m.group(1)) <= n:
            c2, j = int(m.group(1)), m.end()
        out.append(ref(key, c, None, c2))
        if not source:
            # more chapters of the same book: "Ps 67, 51, 130", "Psalms 127 and 128"
            while True:
                m = re.compile(r'(?:,\s*|\s+and\s+|\s+or\s+|\s*/\s*)(\d{1,3})(?![\d\w])'
                               r'(?::(\d{1,3})(?:[-–](\d{1,3}))?)?').match(s, j)
                if not m or NUMBERED_AHEAD.match(s, m.end()) or not 1 <= int(m.group(1)) <= n:
                    break
                c = int(m.group(1))
                out.append(ref(key, c, int(m.group(2)) if m.group(2) else None, None,
                               int(m.group(3)) if m.group(3) else None))
                j = m.end()
    return out, j


